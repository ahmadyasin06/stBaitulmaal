    # ── TOP NAVBAR ──
    st.markdown(
        f"""
        <div class="navbar">
          <div class="navbar-brand">
            {LOGO_IMG_TAG.replace('<img ', '<img class="logo" ')}
            <span>Shadman Town Bait ul Maal
              <small>Muawineen Management</small>
            </span>
          </div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    # ── nav buttons row ──
    nav1, nav2, nav3 = st.columns([1, 1, 4])
    with nav1:
        if st.button(
            "Anat Muawineen",
            use_container_width=True,
            type="primary" if st.session_state["page"] == "anat" else "secondary",
        ):
            st.session_state["page"] = "anat"
            st.rerun()
    with nav2:
        fund_label = "Fund Muawineen" if st.session_state["fund_unlocked"] else "Fund Muawineen"
